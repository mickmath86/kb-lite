// Regenerates supabase/functions/onboarding/keys.ts from the form schema, so the webhook always
// sends the same keys. Run after changing questions:  npx tsx scripts/gen-onboarding-keys.ts
// then redeploy the "onboarding" edge function.
import { writeFileSync } from 'node:fs'
import { STEPS } from '../lib/onboarding/schema'
import { SETUP_STEPS } from '../lib/onboarding/setup-steps'

const answerKeys: string[] = []
const fileKeys: string[] = []
for (const s of STEPS) {
  for (const f of s.fields) {
    if (f.type === 'file') { if (!fileKeys.includes(f.id)) fileKeys.push(f.id) }
    else if (!['note', 'demo', 'ein'].includes(f.type) && !answerKeys.includes(f.id)) answerKeys.push(f.id)
  }
}
const out = `// GENERATED by scripts/gen-onboarding-keys.ts. Do not edit by hand.
// Every webhook payload includes all of these keys (empty string when not answered).
export const ANSWER_KEYS = ${JSON.stringify(answerKeys, null, 2)} as const

export const FILE_KEYS = ${JSON.stringify(fileKeys, null, 2)} as const

export const QUESTION_STEP_IDS = ${JSON.stringify(STEPS.map((s) => s.id), null, 2)} as const

export const SETUP_STEP_IDS = ${JSON.stringify(SETUP_STEPS.map((s) => s.id), null, 2)} as const
`
writeFileSync(new URL('../supabase/functions/onboarding/keys.ts', import.meta.url), out)
console.log(`answers: ${answerKeys.length}, files: ${fileKeys.length}, setup steps: ${SETUP_STEPS.length}`)
